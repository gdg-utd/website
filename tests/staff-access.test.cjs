/* eslint-disable @typescript-eslint/no-require-imports -- Real PostgreSQL permission and mutation tests. */
const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {PGlite}=require('@electric-sql/pglite');

test('staff access enforces admin authority, protects self access, rejects stale edits and audits changes', async()=>{
  const db=new PGlite();
  const admin='11111111-1111-4111-8111-111111111111', reviewer='22222222-2222-4222-8222-222222222222', member='33333333-3333-4333-8333-333333333333';
  await db.exec(`create role anon; create role authenticated; create schema auth; create schema private;
    create table auth.users(id uuid primary key,email text,deleted_at timestamptz);
    create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
    create table public.profiles(id uuid primary key,first_name text,last_name text);
    create table public.application_admins(user_id uuid primary key references auth.users(id),role text default 'admin' check(role in ('admin','reviewer')),active boolean default true,created_at timestamptz default now(),created_by uuid);
    create function private.is_application_admin() returns boolean language sql security definer set search_path='' as $$select exists(select 1 from public.application_admins where user_id=auth.uid() and active and role='admin')$$;
    grant usage on schema private,auth to authenticated; grant execute on function auth.uid(),private.is_application_admin() to authenticated;
    revoke all on public.application_admins from public,anon,authenticated;
    insert into auth.users(id,email) values('${admin}','admin@utdallas.edu'),('${reviewer}','reviewer@utdallas.edu'),('${member}','member@utdallas.edu');
    insert into public.application_admins(user_id,role) values('${admin}','admin'),('${reviewer}','reviewer');`);
  await db.exec(fs.readFileSync('supabase/migrations/20261105053252_add_staff_access_management.sql','utf8'));
  const actAs=async(id)=>{await db.exec(`reset role;select set_config('request.jwt.claim.sub','${id}',false);set role authenticated;`);};
  const set=(email,role,expected)=>db.query('select public.set_staff_access($1,$2,$3)',[email,role,expected]);
  await actAs(reviewer);
  await assert.rejects(db.query('select public.get_staff_access()'),/Administrator access required/);
  await assert.rejects(set('member@utdallas.edu','admin','new'),/Administrator access required/);
  await actAs(member);
  await assert.rejects(set('member@utdallas.edu','admin','new'),/Administrator access required/);
  await actAs(admin);
  await assert.rejects(set('admin@utdallas.edu','revoked','admin'),/own access/);
  await assert.rejects(set('absent@utdallas.edu','reviewer','new'),/No website account/);
  await set(' MEMBER@UTDALLAS.EDU ','reviewer','new');
  await assert.rejects(set('member@utdallas.edu','admin','new'),/already has staff access/);
  await assert.rejects(set('member@utdallas.edu','revoked','admin'),/Access changed/);
  await set('member@utdallas.edu','admin','reviewer');
  await set('member@utdallas.edu','revoked','admin');
  await assert.rejects(set('member@utdallas.edu','reviewer','admin'),/Access changed/);
  await set('member@utdallas.edu','reviewer','new');
  const result=(await db.query('select public.get_staff_access() as data')).rows[0].data;
  assert.equal(result.members.length,3);assert.equal(result.events.length,4);
  assert.equal(result.members.find(m=>m.email==='member@utdallas.edu').role,'reviewer');
  assert.ok(result.events.every(e=>e.actor_email==='admin@utdallas.edu'));
  await assert.rejects(db.query('select * from public.staff_access_events'),/permission denied/);
  await assert.rejects(db.query("update public.application_admins set role='admin'"),/permission denied/);
  await actAs(member);
  await assert.rejects(db.query('select private.get_staff_access()'),/Administrator access required/);
  await db.exec('reset role;set role anon;');
  await assert.rejects(db.query('select public.get_staff_access()'),/permission denied/);
  await db.exec('reset role');
  assert.equal((await db.query(`select count(*)::int as n from public.application_admins where active and role='admin'`)).rows[0].n,1);
  await db.close();
});
