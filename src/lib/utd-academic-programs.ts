export type UtdDegree = keyof typeof UTD_ACADEMIC_PROGRAMS;

export const UTD_DEGREES = Object.keys(UTD_ACADEMIC_PROGRAMS) as UtdDegree[];

export function isUtdDegree(value: string): value is UtdDegree {
  return Object.hasOwn(UTD_ACADEMIC_PROGRAMS, value);
}

export function getUtdMajors(degree: string): readonly string[] {
  return isUtdDegree(degree) ? UTD_ACADEMIC_PROGRAMS[degree] : [];
}

export function isValidUtdProgram(degree: string, major: string) {
  return isUtdDegree(degree) && getUtdMajors(degree).includes(major as never);
}
